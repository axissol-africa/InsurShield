import { afterAll, beforeAll, expect, it } from 'vitest';
import { eq } from 'drizzle-orm';
import { buildCustomer, buildPurchasedPolicy, buildStaffUser } from '../../test/builders.js';
import { startApp, type TestApp } from '../../test/helpers.js';
import { signIn } from '../../test/sessions.js';
import { insurerReviews, reviewRevisions, reviewDecisions, notifications } from '../db/schema.js';
let app: TestApp;
beforeAll(async () => { app = await startApp(); });
afterAll(async () => { await app?.close(); });

it('validates customer input, protects private reads, and resolves through the admin route with a notification', async () => {
  const customer = await buildCustomer(app.db);
  const purchase = await buildPurchasedPolicy(app.db, { customer });
  const moderator = await buildStaffUser(app.db);
  const reviewer = await buildStaffUser(app.db);
  const asCustomer = await signIn(app.http, customer);
  const asAdmin = await signIn(app.http, reviewer);
  const asModerator = await signIn(app.http, moderator);
  const [review] = await app.db.insert(insurerReviews).values({ policyNumber: purchase.policy.policyNumber }).returning();
  const [revision] = await app.db.insert(reviewRevisions).values({ reviewId: review.id, kind: 'REVIEW', version: 1, status: 'REJECTED', rating: 3, text: 'Review', retiredAt: new Date() }).returning();
  const [decision] = await app.db.insert(reviewDecisions).values({ revisionId: revision.id, action: 'REJECT', reason: 'MODERATION', moderatorId: moderator.id }).returning();
  await app.http.post('/api/v1/review-appeals').set(asCustomer).send({ decisionId: decision.id, reason: '' }).expect(400);
  const created = await app.http.post('/api/v1/review-appeals').set(asCustomer).send({ decisionId: decision.id, reason: 'Please reconsider', evidence: 'Private supporting detail' }).expect(201);
  await app.http.post('/api/v1/review-appeals').set(asCustomer).send({ decisionId: decision.id, reason: 'Duplicate' }).expect(409);
  const owned = await app.http.get('/api/v1/review-appeals').query({ decisionId: decision.id }).set(asCustomer).expect(200);
  expect(owned.body).toEqual([expect.objectContaining({ id: created.body.id })]);
  const later = await app.http.get('/api/v1/review-appeals').query({ page: 2 }).set(asCustomer).expect(200);
  expect(later.body).toEqual([]);
  await app.http.get('/api/v1/review-appeals').query({ page: 0 }).set(asCustomer).expect(400);
  await app.http.get('/api/v1/admin/review-appeals').set(asCustomer).expect(403);
  const adminList = await app.http.get('/api/v1/admin/review-appeals').set(asAdmin).expect(200);
  expect(adminList.body).toEqual(expect.arrayContaining([expect.objectContaining({ id: created.body.id, reviewId: review.id })]));
  await app.http.patch(`/api/v1/admin/review-appeals/reviews/${review.id}/legal-hold`).set(asAdmin).send({ held: true }).expect(200);
  const path = `/api/v1/admin/review-appeals/${created.body.id}/resolve`;
  await app.http.post(path).set(asModerator).send({ outcome: 'UPHELD', reason: 'Original moderator' }).expect(403);
  const resolved = await app.http.post(path).set(asAdmin).send({ outcome: 'UPHELD', reason: 'Reviewed independently' }).expect(201);
  expect(resolved.body).toMatchObject({ outcome: 'UPHELD', applied: false });
  const history = await app.http.get('/api/v1/review-appeals').query({ reviewId: review.id }).set(asCustomer).expect(200);
  expect(history.body).toEqual([expect.objectContaining({ id: created.body.id, outcome: 'UPHELD', outcomeReason: 'Reviewed independently' })]);
  const otherCustomer = await buildCustomer(app.db);
  const asOtherCustomer = await signIn(app.http, otherCustomer);
  const privateHistory = await app.http.get('/api/v1/review-appeals').query({ reviewId: review.id }).set(asOtherCustomer).expect(200);
  expect(privateHistory.body).toEqual([]);
  const otherPurchase = await buildPurchasedPolicy(app.db, { customer });
  const [otherReview] = await app.db.insert(insurerReviews).values({ policyNumber: otherPurchase.policy.policyNumber }).returning();
  const unrelated = await app.http.get('/api/v1/review-appeals').query({ reviewId: otherReview.id }).set(asCustomer).expect(200);
  expect(unrelated.body).toEqual([]);
  await app.http.get('/api/v1/review-appeals').query({ reviewId: 'invalid' }).set(asCustomer).expect(400);
  const notices = await app.db.select().from(notifications).where(eq(notifications.customerId, customer.id));
  expect(notices).toEqual(expect.arrayContaining([expect.objectContaining({ templateKey: 'REVIEW_APPEAL_DECIDED' })]));
});
