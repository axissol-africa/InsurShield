import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ClientBase } from 'pg';
import {
  applyMigrationFiles,
  createScratchDatabase,
  DRIZZLE_FOLDER,
  migrationFileTags,
  type ScratchDatabase,
} from './scratch-database.js';

/**
 * The migration that gives the insurers predating onboarding their licence
 * records. It is worth its own check because it is the only thing standing
 * between a licence-present rule and a fan-out list with nothing in it: if this
 * does not reach every trading insurer, every quote request is refused.
 *
 * So the database here is built the way a real one is -- migrated to the state
 * before, then filled with rows -- rather than migrated once and filled after,
 * which is the shape that would let a data migration pass while touching
 * nothing.
 */
const TAGS = migrationFileTags();
const GRANDFATHER = '0018_grandfather_insurer_licences';
const BEFORE = TAGS.indexOf(GRANDFATHER);

if (BEFORE < 0) throw new Error(`Expected migration ${GRANDFATHER} to exist.`);

const applyStatements = async (client: ClientBase, tag: string) => {
  for (const statement of statementsOf(tag)) await client.query(statement);
};

const statementsOf = (tag: string) =>
  readFileSync(join(DRIZZLE_FOLDER, `${tag}.sql`), 'utf8')
    .split('--> statement-breakpoint')
    .map((part) => part.replace(/^\s*--.*$/gm, '').trim())
    .filter((part) => part !== '');

// The id is generated by the application, not by a column default, so raw SQL
// supplies one -- which is why the migration itself calls gen_random_uuid().
const insurer = (name: string, status: string, licenceExpiry: string | null) =>
  `INSERT INTO "insurers" ("id", "name", "status", "rateBps", "quoteValidityDays", "coverage", "licenceExpiry", "updatedAt")
     VALUES (gen_random_uuid(), '${name}', '${status}', 525, 14, 'Comprehensive',
             ${licenceExpiry ? `'${licenceExpiry}'` : 'NULL'}, now())`;

describe(`${GRANDFATHER}`, () => {
  let db: ScratchDatabase;

  /** A connection per piece of work, as the other migration specs do. */
  async function query<T>(run: (client: ClientBase) => Promise<T>): Promise<T> {
    const client = await db.connect();
    try {
      return await run(client);
    } finally {
      await client.end();
    }
  }

  beforeAll(async () => {
    db = await createScratchDatabase('grandfather');
    await query(async (client) => {
      // The database as it stands before this migration, then the rows it has to fix.
      await applyMigrationFiles(client, BEFORE);
      await client.query(insurer('Trading Assurance', 'ACTIVE', null));
      await client.query(insurer('Stopped Assurance', 'INACTIVE', null));
      await client.query(insurer('Removed Assurance', 'DELETED', null));
      await client.query(insurer('Licensed Assurance', 'ACTIVE', '2028-01-31'));
      await applyStatements(client, GRANDFATHER);
    });
  });

  afterAll(async () => {
    await db.drop();
  });

  const insurerRow = (name: string) =>
    query(async (client) => {
      const { rows } = await client.query<{ id: string; licenceExpiry: Date | null; licenceNumber: string | null }>(
        'SELECT "id", "licenceExpiry", "licenceNumber" FROM "insurers" WHERE "name" = $1',
        [name],
      );
      return rows[0];
    });

  const licenceOf = (insurerId: string) =>
    query(async (client) => {
      const { rows } = await client.query<{
        documentId: string | null;
        expiresAt: string | null;
        state: string;
        note: string | null;
      }>(
        // As text, so the assertion reads as the calendar day the column holds.
        `SELECT "documentId", "expiresAt"::text AS "expiresAt", "state", "note" FROM "insurer_evidence"
          WHERE "insurerId" = $1 AND "kind" = 'LICENCE'`,
        [insurerId],
      );
      return rows;
    });

  it('gives an insurer with no licence an expiry, so the fan-out list keeps it', async () => {
    const row = await insurerRow('Trading Assurance');

    expect(row.licenceExpiry?.toISOString()).toBe('2027-03-31T00:00:00.000Z');
  });

  it('gives it an approved licence on file, so activation admits it', async () => {
    const row = await insurerRow('Trading Assurance');

    const [licence] = await licenceOf(row.id);
    expect(licence).toMatchObject({ state: 'APPROVED', expiresAt: '2027-03-31' });
  });

  it('leaves the record saying what it is: no document, and no licence number', async () => {
    const row = await insurerRow('Trading Assurance');

    const [licence] = await licenceOf(row.id);
    expect(licence.documentId, 'nobody has produced a scan').toBeNull();
    expect(row.licenceNumber, 'nor a number').toBeNull();
    expect(licence.note).toContain('grandfather');
  });

  it('reaches an insurer that is not trading, which may be reinstated later', async () => {
    const row = await insurerRow('Stopped Assurance');

    expect(row.licenceExpiry).not.toBeNull();
    expect(await licenceOf(row.id)).toHaveLength(1);
  });

  it('leaves a removed insurer alone, since reviving one goes through onboarding', async () => {
    const row = await insurerRow('Removed Assurance');

    expect(row.licenceExpiry).toBeNull();
    expect(await licenceOf(row.id)).toEqual([]);
  });

  it('does not overwrite a licence somebody had already recorded', async () => {
    const row = await insurerRow('Licensed Assurance');

    expect(row.licenceExpiry?.toISOString()).toBe('2028-01-31T00:00:00.000Z');
    expect(await licenceOf(row.id), 'but it still gains the record activation reads').toHaveLength(1);
  });

  it('is safe to run twice, as a replayed deployment would', async () => {
    await query((client) => applyStatements(client, GRANDFATHER));

    const row = await insurerRow('Trading Assurance');
    expect(await licenceOf(row.id), 'one licence, not two').toHaveLength(1);
  });
});
