import { beforeEach, expect, it, vi } from 'vitest';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import ClaimTimeline from './ClaimTimeline';
import { api } from '@/api';
vi.mock('@/api', () => ({ api: { claims: { timeline: vi.fn(), insurerTimeline: vi.fn(), update: vi.fn(), submitEvidence: vi.fn() }, documents: { upload: vi.fn() } } }));
const detail = { revision: 'event-1', claimNumber: 'CLM-1', status: 'Under review', insurerClaimReference: 'INS-1', responseDueOn: '2026-12-01', updates: [] };
beforeEach(() => { vi.resetAllMocks(); api.claims.timeline.mockResolvedValue(detail); api.claims.insurerTimeline.mockResolvedValue(detail); });
it('shows references and gates insurer updates behind a customer message', async () => {
  const user = userEvent.setup();
  api.claims.update.mockResolvedValue({ ...detail, status: 'Additional information required' });
  render(<ClaimTimeline claimNumber="CLM-1" insurer />);
  expect(await screen.findByText('Insurer reference: INS-1')).toBeVisible();
  expect(screen.getByRole('button', { name: 'Request evidence' })).toBeDisabled();
  await user.type(screen.getByLabelText('Message to customer'), 'Please supply photos');
  await user.type(screen.getByLabelText('Evidence needed'), 'Damage photos');
  await user.click(screen.getByRole('button', { name: 'Request evidence' }));
  expect(api.claims.update).toHaveBeenCalledWith('CLM-1', { expectedRevision: 'event-1', action: 'REQUEST_EVIDENCE', message: 'Please supply photos', evidenceRequest: 'Damage photos' }, expect.any(String));
  expect(await screen.findByText('Additional information required')).toBeVisible();
});
it('uploads requested evidence and returns the customer to review', async () => {
  const user = userEvent.setup();
  api.claims.timeline.mockResolvedValue({ ...detail, status: 'Additional information required' });
  api.documents.upload.mockResolvedValue({ id: 'DOC-1' });
  api.claims.submitEvidence.mockResolvedValue(detail);
  render(<ClaimTimeline claimNumber="CLM-1" />);
  const input = await screen.findByLabelText('Requested evidence files');
  const file = new File(['photo'], 'damage.jpg', { type: 'image/jpeg' });
  await user.upload(input, file);
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(api.documents.upload).toHaveBeenCalledWith(file, 'CLAIM_ATTACHMENT');
  expect(api.claims.submitEvidence).toHaveBeenCalledWith('CLM-1', { expectedRevision: 'event-1', documentIds: ['DOC-1'] }, expect.any(String));
  expect(await screen.findByText('Under review')).toBeVisible();
  expect(screen.queryByLabelText('Requested evidence files')).not.toBeInTheDocument();
});
it('retains typed update after failure and permits retry', async () => {
  const user = userEvent.setup();
  api.claims.update.mockRejectedValue(new Error('Claim changed. Refresh updates.'));
  render(<ClaimTimeline claimNumber="CLM-1" insurer />);
  await user.type(await screen.findByLabelText('Message to customer'), 'Decision reason');
  await user.click(screen.getByRole('button', { name: 'Decline' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Claim changed');
  expect(screen.getByLabelText('Message to customer')).toHaveValue('Decision reason');
});

it('reuses the lifecycle command key on retry and rotates it when the action or draft changes', async () => {
  const user = userEvent.setup();
  api.claims.update.mockRejectedValue(new Error('Network unavailable'));
  render(<ClaimTimeline claimNumber="CLM-1" insurer />);
  await user.type(await screen.findByLabelText('Message to customer'), 'Decision');
  await user.click(screen.getByRole('button', { name: 'Approve' }));
  await screen.findByRole('alert');
  await user.click(screen.getByRole('button', { name: 'Approve' }));
  expect(api.claims.update.mock.calls[1]).toEqual(api.claims.update.mock.calls[0]);
  await user.click(screen.getByRole('button', { name: 'Decline' }));
  expect(api.claims.update.mock.calls[2][2]).not.toBe(api.claims.update.mock.calls[1][2]);
  await user.type(screen.getByLabelText('Message to customer'), ' updated');
  await user.click(screen.getByRole('button', { name: 'Decline' }));
  expect(api.claims.update.mock.calls[3][2]).not.toBe(api.claims.update.mock.calls[2][2]);
});
it('retains successful partial uploads and reuses document ids and key after a lost response', async () => {
  const user = userEvent.setup();
  api.claims.timeline.mockResolvedValue({ ...detail, status: 'Additional information required' });
  api.documents.upload.mockResolvedValueOnce({ id: 'DOC-1' }).mockRejectedValueOnce(new Error('Upload failed')).mockResolvedValueOnce({ id: 'DOC-2' });
  api.claims.submitEvidence.mockRejectedValueOnce(new Error('Response lost')).mockResolvedValue({ ...detail, revision: 'event-2' });
  render(<ClaimTimeline claimNumber="CLM-1" />);
  const files = [new File(['a'], 'a.jpg'), new File(['b'], 'b.jpg')];
  await user.upload(await screen.findByLabelText('Requested evidence files'), files);
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Upload failed');
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Response lost');
  const sent = api.claims.submitEvidence.mock.calls[0];
  expect(sent[1]).toEqual({ expectedRevision: 'event-1', documentIds: ['DOC-1', 'DOC-2'] });
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(api.documents.upload).toHaveBeenCalledTimes(3);
  expect(api.claims.submitEvidence.mock.calls[1]).toEqual(sent);
});
it('requires refresh after a revision conflict and does not reuse evidence for a new request', async () => {
  const user = userEvent.setup();
  api.claims.timeline.mockResolvedValueOnce({ ...detail, status: 'Additional information required' }).mockResolvedValue({ ...detail, revision: 'new-request', status: 'Additional information required' });
  api.documents.upload.mockResolvedValueOnce({ id: 'OLD-DOC' }).mockResolvedValueOnce({ id: 'NEW-DOC' });
  api.claims.submitEvidence.mockRejectedValueOnce(Object.assign(new Error('Stale'), { code: 'CLAIM_REVISION_CHANGED' })).mockResolvedValue({ ...detail, revision: 'new-event' });
  render(<ClaimTimeline claimNumber="CLM-1" />);
  const file = new File(['a'], 'a.jpg');
  await user.upload(await screen.findByLabelText('Requested evidence files'), file);
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Refresh updates');
  expect(screen.getByRole('button', { name: 'Submit evidence' })).toBeDisabled();
  await user.click(screen.getByRole('button', { name: 'Refresh updates' }));
  await screen.findByLabelText('Requested evidence files');
  expect(screen.getByRole('button', { name: 'Submit evidence' })).toBeDisabled();
  expect(screen.getByLabelText('Requested evidence files').files).toHaveLength(0);
  await user.upload(screen.getByLabelText('Requested evidence files'), file);
  await user.click(screen.getByRole('button', { name: 'Submit evidence' }));
  expect(api.claims.submitEvidence.mock.calls[1][1]).toEqual({ expectedRevision: 'new-request', documentIds: ['NEW-DOC'] });
  expect(api.claims.submitEvidence.mock.calls[1][2]).not.toBe(api.claims.submitEvidence.mock.calls[0][2]);
});
it('preserves an insurer draft through revision refresh but uses a new command key', async () => {
  const user = userEvent.setup();
  api.claims.insurerTimeline.mockResolvedValueOnce(detail).mockResolvedValue({ ...detail, revision: 'event-2' });
  api.claims.update.mockRejectedValue(Object.assign(new Error('Stale'), { code: 'CLAIM_REVISION_CHANGED' }));
  render(<ClaimTimeline claimNumber="CLM-1" insurer />);
  await user.type(await screen.findByLabelText('Message to customer'), 'Reason');
  await user.click(screen.getByRole('button', { name: 'Approve' }));
  await screen.findByRole('alert');
  expect(screen.getByRole('button', { name: 'Approve' })).toBeDisabled();
  await user.click(screen.getByRole('button', { name: 'Refresh updates' }));
  expect(screen.getByLabelText('Message to customer')).toHaveValue('Reason');
  await user.click(screen.getByRole('button', { name: 'Approve' }));
  expect(api.claims.update.mock.calls[1][1].expectedRevision).toBe('event-2');
  expect(api.claims.update.mock.calls[1][2]).not.toBe(api.claims.update.mock.calls[0][2]);
});
